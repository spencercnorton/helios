def classify_notification(method: str) -> NotificationDisposition:
    """Return the pinned-schema disposition for one server notification."""

    if method in HANDLED_NOTIFICATION_METHODS:
        return "handled"
    if method in IGNORED_NOTIFICATION_METHODS:
        return "ignored"
    if method in UNSUPPORTED_NOTIFICATION_METHODS:
        return "unsupported"
    return "unknown"


def classify_server_request(method: str) -> ServerRequestDisposition:
    """Return the pinned-schema disposition for one server request."""

    if method in SUPPORTED_SERVER_REQUEST_METHODS:
        return "supported"
    if method in DENIED_SERVER_REQUEST_METHODS:
        return "denied"
    return "unknown"


def unsupported_notification_message(method: str) -> str:
    """Return a stable user-facing consequence for a known capability gap."""

    return UNSUPPORTED_NOTIFICATION_METHODS.get(
        method,
        f"a known Codex event is not supported ({method})",
    )
