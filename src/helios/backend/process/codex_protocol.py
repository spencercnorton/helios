"""Versioned Codex App Server method registry.

The App Server protocol is generated by the installed Codex CLI, but Helios's
CI intentionally has no Codex binary.  ``docs/protocol`` therefore contains a
compact generated method manifest.  The registry below classifies every
server-to-client method in that manifest so an upgrade has three explicit
outcomes:

* handled -- Helios consumes the method;
* ignored -- the method belongs to a surface Helios deliberately does not use;
* unsupported -- the method can affect an active session, but Helios does not
  yet project it and must report that limitation.

Only a method absent from the generated schema is protocol drift.  Keep this
module GTK-free so the manifest/registry contract runs in python-slim CI.
"""

